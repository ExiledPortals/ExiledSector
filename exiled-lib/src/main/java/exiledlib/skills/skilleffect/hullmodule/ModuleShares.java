    private static final Map<String, ModuleShare> BY_NAME = build();

    private ModuleShares() {
    }

    public static ModuleShare of(SkillEffect effect) {
        return BY_NAME.getOrDefault(effect.name(), ModuleShare.EXCLUDE);
    }

    static Set<String> classifiedNames() {
        return Collections.unmodifiableSet(BY_NAME.keySet());
    }

    private static Map<String, ModuleShare> build() {
        Map<String, ModuleShare> byName = new HashMap<>();
        classify(byName, SHARED, ModuleShare.SHARE);
        classify(byName, SHARED_WITH_REBUILD, ModuleShare.SHARE_REBUILD);
        classify(byName, SKIPPED_ON_MODULES, ModuleShare.SKIP);
        classify(byName, MISBEHAVE_ON_MODULES, ModuleShare.EXCLUDE);
        classify(byName, UNTESTED_ON_MODULES, ModuleShare.EXCLUDE);
        return byName;
    }

    private static void classify(Map<String, ModuleShare> byName, List<String> names, ModuleShare share) {
        for (String name : names) {
            if (byName.put(name, share) != null) {
                throw new IllegalStateException("Effect classified twice for modules: " + name);
            }
        }
    }
